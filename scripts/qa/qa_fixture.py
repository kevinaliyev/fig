"""Fig QA Test Fixture & Dummy Dotfile Repository Generator.

Scaffolds a clean, standardized, cross-platform dummy dotfiles repository
specifically designed for verifying Fig's linking, packaging, collision,
and bootstrap capabilities across Windows, Linux, and macOS.
"""

from __future__ import annotations

import os
import sys
import shutil
import argparse
import subprocess
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

DEFAULT_FIXTURE_DIR = REPO_ROOT / "tests" / "fixtures" / "dummy_dotfiles"
DEFAULT_BARE_DIR = REPO_ROOT / "tests" / "fixtures" / "dummy_dotfiles.git"


BASHRC_CONTENT = """# Fig QA Test Dotfile (.bashrc)
fig_test() {
    echo "=== Fig QA: .bashrc linked successfully on $(uname -s 2>/dev/null || echo POSIX) ==="
    echo "Home directory: $HOME"
    echo "Date: $(date 2>/dev/null || echo unknown)"
}
"""

ZSHRC_CONTENT = """# Fig QA Test Dotfile (.zshrc)
fig_test() {
    echo "=== Fig QA: .zshrc linked successfully on $(uname -s 2>/dev/null || echo macOS) ==="
    echo "Home directory: $HOME"
    echo "Date: $(date 2>/dev/null || echo unknown)"
}
"""

GITCONFIG_CONTENT = """[user]
    name = Fig QA Tester
    email = qa@fig.local
[alias]
    figtest = "!echo Fig gitconfig linked successfully on host: $(uname -s 2>/dev/null || echo Windows)"
"""

PWSH_PROFILE_CONTENT = """# Fig QA Test Dotfile (PowerShell Profile)
function fig-test {
    Write-Host "=== Fig QA: PowerShell profile linked successfully ===" -ForegroundColor Green
    Write-Host "PROFILE path: $PROFILE" -ForegroundColor Cyan
    Write-Host "Operating System: $env:OS" -ForegroundColor Gray
}
"""

NVIM_INIT_CONTENT = """-- Fig QA Test Dotfile (Neovim Config)
print("=== Fig QA: Neovim config loaded successfully from directory package! ===")
"""

NVIM_SUB_CONTENT = """-- Sub-module test file for nested tree verification
return { status = "active", test = "passed" }
"""

FIXTURE_README = """# Dummy Cross-Platform Dotfiles Repository for Fig QA

This repository is generated by `scripts/qa_fixture.py` to test all Fig features:

| Item | Repo Source | Expected Destination | Test Command |
| :--- | :--- | :--- | :--- |
| `.bashrc` | `.bashrc` | `~/.bashrc` | `source ~/.bashrc && fig_test` |
| `.zshrc` | `.zshrc` | `~/.zshrc` | `source ~/.zshrc && fig_test` |
| `.gitconfig` | `.gitconfig` | `~/.gitconfig` | `git figtest` |
| `pwsh/` | `pwsh/` | `~/Documents/PowerShell/` (Win) or `~/.config/powershell/` | `. $PROFILE; fig-test` |
| `nvim/` | `nvim/` | `~/.config/nvim/` or `%LOCALAPPDATA%/nvim` | `nvim` (prints message) |
"""


def create_fixture_files(target_dir: Path) -> None:
    """Writes the dummy dotfile files into target_dir."""
    target_dir.mkdir(parents=True, exist_ok=True)

    # 1. Root dotfiles
    (target_dir / ".bashrc").write_text(BASHRC_CONTENT, encoding="utf-8")
    (target_dir / ".zshrc").write_text(ZSHRC_CONTENT, encoding="utf-8")
    (target_dir / ".gitconfig").write_text(GITCONFIG_CONTENT, encoding="utf-8")
    (target_dir / "README.md").write_text(FIXTURE_README, encoding="utf-8")

    # 2. PowerShell profile package
    pwsh_dir = target_dir / "pwsh"
    pwsh_dir.mkdir(parents=True, exist_ok=True)
    (pwsh_dir / "Microsoft.PowerShell_profile.ps1").write_text(PWSH_PROFILE_CONTENT, encoding="utf-8")

    # 3. Neovim modular config package
    nvim_dir = target_dir / "nvim"
    nvim_lua_dir = nvim_dir / "lua" / "config"
    nvim_lua_dir.mkdir(parents=True, exist_ok=True)
    (nvim_dir / "init.lua").write_text(NVIM_INIT_CONTENT, encoding="utf-8")
    (nvim_lua_dir / "init.lua").write_text(NVIM_SUB_CONTENT, encoding="utf-8")

    print(f"[OK] Created dummy dotfile fixture at: {target_dir}")


def init_git_repo(target_dir: Path) -> None:
    """Initializes git repo and makes initial commit in target_dir."""
    git_bin = shutil.which("git")
    if not git_bin:
        print("[!] Git executable not found on PATH. Skipping git repo initialization.", file=sys.stderr)
        return

    try:
        subprocess.run([git_bin, "init", "-b", "main"], cwd=str(target_dir), check=True, capture_output=True, text=True)
    except subprocess.CalledProcessError:
        # Fallback for older git versions that do not support -b main
        subprocess.run([git_bin, "init"], cwd=str(target_dir), check=True, capture_output=True, text=True)

    # Set local dummy identity so commit succeeds even on fresh VMs
    subprocess.run([git_bin, "config", "user.name", "Fig QA"], cwd=str(target_dir), check=True, capture_output=True)
    subprocess.run([git_bin, "config", "user.email", "qa@fig.local"], cwd=str(target_dir), check=True, capture_output=True)

    subprocess.run([git_bin, "add", "."], cwd=str(target_dir), check=True, capture_output=True)
    subprocess.run([git_bin, "commit", "-m", "Initial dummy cross-platform dotfiles commit for Fig QA"], cwd=str(target_dir), check=True, capture_output=True)

    print(f"[OK] Initialized Git repository with initial commit in: {target_dir}")


def create_bare_remote(source_dir: Path, bare_dir: Path) -> None:
    """Clones a bare copy of source_dir to bare_dir to act as a local Git remote."""
    git_bin = shutil.which("git")
    if not git_bin:
        print("[!] Git executable not found on PATH.", file=sys.stderr)
        return

    if bare_dir.exists():
        shutil.rmtree(bare_dir)

    bare_dir.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([git_bin, "clone", "--bare", str(source_dir), str(bare_dir)], check=True, capture_output=True)
    print(f"[OK] Created bare local Git remote at: {bare_dir}")
    print(f"     Test with: fig bootstrap file://{bare_dir.as_posix()} --dest ~/test-dotfiles")


def create_collision_files() -> None:
    """Creates mock colliding files in user home to test Fig's collision detection and backups."""
    home = Path.home()
    collision_header = "# MOCK COLLISION PRE-EXISTING FILE - should be backed up to ~/.fig/backups/ by fig\n"

    targets = [
        home / ".gitconfig",
        home / ".bashrc",
        home / ".zshrc",
    ]

    created = []
    for t in targets:
        if not t.exists():
            t.write_text(collision_header, encoding="utf-8")
            created.append(t)
        else:
            print(f"[*] Skipped existing file (won't overwrite your actual config): {t}")

    if created:
        print(f"[OK] Created {len(created)} mock collision file(s) in $HOME:")
        for c in created:
            print(f"     {c}")
    else:
        print("[*] No collision files created (destination files already exist).")


def clean_fixtures(target_dir: Path, bare_dir: Path) -> None:
    """Removes fixture directories."""
    cleaned = 0
    if target_dir.exists():
        shutil.rmtree(target_dir)
        print(f"[OK] Removed fixture directory: {target_dir}")
        cleaned += 1
    if bare_dir.exists():
        shutil.rmtree(bare_dir)
        print(f"[OK] Removed bare repository: {bare_dir}")
        cleaned += 1
    if cleaned == 0:
        print("[*] No fixtures found to clean.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Fig QA Dummy Cross-Platform Dotfile Repository Generator")
    parser.add_argument("path", nargs="?", default=str(DEFAULT_FIXTURE_DIR), help="Destination path for dummy dotfile repo")
    parser.add_argument("--bare", action="store_true", help="Also generate a bare Git repo to test remote cloning without internet")
    parser.add_argument("--collisions", action="store_true", help="Generate mock collision files in user home to test backup vault")
    parser.add_argument("--clean", action="store_true", help="Delete generated dummy fixtures")
    parser.add_argument("--no-git", action="store_true", help="Do not initialize a Git repository")

    args = parser.parse_args()
    target_path = Path(args.path).resolve()
    bare_path = DEFAULT_BARE_DIR

    if args.clean:
        clean_fixtures(target_path, bare_path)
        return 0

    if args.collisions:
        create_collision_files()

    create_fixture_files(target_path)

    if not args.no_git:
        init_git_repo(target_path)
        if args.bare:
            create_bare_remote(target_path, bare_path)

    print("\nNext Steps for Testing:")
    print(f"  1. Test Builder:    fig build {target_path}")
    print(f"  2. Test Bootstrap:  fig bootstrap {target_path}")
    if args.bare:
        print(f"  3. Test Remote Git: fig bootstrap file://{bare_path.as_posix()} --dest ~/my-dotfiles")
    print("  4. Verify Linkage:  git figtest  OR  source ~/.bashrc && fig_test")
    return 0


if __name__ == "__main__":
    sys.exit(main())
