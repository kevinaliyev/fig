def build_template_from_items(
    repo_root: Path,
    items: List[DiscoveredConfig],
    is_system: bool = False,
    existing_template: Optional[Template] = None,
) -> Template:
    """Assemble or update a Template object from reviewed items."""
    tpl = existing_template or Template(
        name=repo_root.name or "dotfiles",
        version="1.0.0",
        description=f"Generated by Fig Builder for {repo_root.name}",
        link_mode="auto",
        backup_on_collision=True,
        source_file=repo_root / "fig.toml",
    )

    if is_system:
        for item in items:
            if item.is_excluded:
                continue
            if not item.dest_expr or not item.dest_expr.strip():
                raise ValueError(f"Every system spec must include an explicit destination pathspec: {item.source_rel}")
            if item.os_target:
                os_key = item.os_target.lower()
                tpl.os_system_mappings.setdefault(os_key, {})[item.source_rel] = item.dest_expr
            else:
                tpl.system_mappings[item.source_rel] = item.dest_expr
        return tpl

    # User dotfiles mode
    universal_mappings: Dict[str, Any] = {}
    ignored_patterns: List[str] = list(tpl.ignore_patterns)

    def _make_val(dest_expr: str, link_mode: Optional[str]) -> Union[str, Dict[str, str]]:
        if link_mode:
            return {"target": dest_expr, "mode": link_mode}
        return dest_expr

    def _add_mapping(source_rel: str, dest_expr: str, os_target: Optional[str], link_mode: Optional[str]):
        val = _make_val(dest_expr, link_mode)
        if os_target:
            tpl.os_mappings.setdefault(os_target.lower(), {})[source_rel] = val
        elif CURRENT_OS == OperatingSystem.WINDOWS and (
            "Documents/PowerShell" in dest_expr
            or "%APPDATA%" in dest_expr
            or "%LOCALAPPDATA%" in dest_expr
        ):
            tpl.os_mappings.setdefault(OperatingSystem.WINDOWS.value, {})[source_rel] = val
        else:
            universal_mappings[source_rel] = val

    for item in items:
        # Check active leaves
        all_leaves = get_all_leaf_items(item)
        active_leaves = [l for l in all_leaves if not l.is_excluded]

        if item.is_excluded and not active_leaves:
            ignored_patterns.append(item.source_rel)
            continue

        if not item.is_directory:
            # Standalone root file
            _add_mapping(item.source_rel, item.dest_expr, item.os_target, item.link_mode)
        else:
            # Directory package: check if user packed it or if it's customized/unpacked
            if not item.is_excluded and ((item.link_as_dir and not is_package_customized(item)) or getattr(item, "force_pack", False)):
                # Stow-style recursive directory link
                _add_mapping(item.source_rel, item.dest_expr, item.os_target, item.link_mode)
                for leaf in all_leaves:
                    if leaf.is_excluded:
                        ignored_patterns.append(leaf.source_rel)
            else:
                # User customized individual child items or unpacked directory: link active leaves individually!
                for leaf in all_leaves:
                    if leaf.is_excluded:
                        ignored_patterns.append(leaf.source_rel)
                    else:
                        leaf_os = leaf.os_target or item.os_target
                        leaf_mode = leaf.link_mode or item.link_mode
                        _add_mapping(leaf.source_rel, leaf.dest_expr, leaf_os, leaf_mode)

    # Collect all active mapped sources and package root names
    active_sources: set[str] = set(universal_mappings.keys())
    for os_map in tpl.os_mappings.values():
        active_sources.update(os_map.keys())

    # Build clean ignore list: preserve base/custom ignores and explicitly excluded items,
    # but strictly purge any pattern that conflicts with currently active packages or mapped sources
    active_tokens: set[str] = set()
    for s in active_sources:
        active_tokens.add(s)
        parts = s.replace("\\", "/").split("/")
        if parts:
            active_tokens.add(parts[0])

    clean_ignores = [p for p in ignored_patterns if p not in active_tokens]

    tpl.mappings = universal_mappings
    tpl.presets = existing_template.presets if existing_template else []
    tpl.ignore_patterns = sorted(set(clean_ignores))
    return tpl


def merge_existing_template_into_discovered(
    discovered: List[DiscoveredConfig],
    template: Template,
) -> List[DiscoveredConfig]:
    """Pre-populate discovered scanner items with existing template configurations,
    preserving custom destination expressions, individual link modes, OS target scopes,
    explicit unpack/pack states, and exclusions so the user can rebuild or edit their
    template directly inside the REPL without starting from scratch.
    """
    def _extract_spec(val: Any) -> Tuple[str, Optional[str]]:
        if isinstance(val, dict):
            return str(val.get("target", "")), val.get("mode")
        return str(val), None

    # Map of source_rel -> (dest_expr, link_mode, os_target)
    all_specs: Dict[str, Tuple[str, Optional[str], Optional[str]]] = {}

    for src, val in template.mappings.items():
        dest, mode = _extract_spec(val)
        all_specs[src] = (dest, mode, None)

    for os_name, os_map in template.os_mappings.items():
        for src, val in os_map.items():
            dest, mode = _extract_spec(val)
            all_specs[src] = (dest, mode, os_name)

    for src, val in template.system_mappings.items():
        dest, mode = _extract_spec(val)
        all_specs[src] = (dest, mode, None)

    for os_name, os_map in template.os_system_mappings.items():
        for src, val in os_map.items():
            dest, mode = _extract_spec(val)
            all_specs[src] = (dest, mode, os_name)

    ignore_set = set(template.ignore_patterns)
    matched_specs: Set[str] = set()

    def _apply_item(item: DiscoveredConfig, parent_packed: bool = False) -> None:
        src = item.source_rel
        is_packed_dir = False
        if src in all_specs:
            dest, mode, os_target = all_specs[src]
            matched_specs.add(src)
            item.is_excluded = False
            if dest:
                item.dest_expr = dest
            if mode:
                item.link_mode = mode
            if os_target:
                item.os_target = os_target
            item.customized = True
            if item.is_directory:
                item.link_as_dir = True
                item.force_pack = True
                is_packed_dir = True
        elif src in ignore_set or Path(src).name in ignore_set:
            item.is_excluded = True
            item.customized = True
        elif parent_packed:
            # Ancestor directory is mapped as a whole packed directory in the template;
            # its children are included automatically unless explicitly in ignore_set.
            item.is_excluded = False
        elif all_specs:
            # If template has explicit mappings and this item is not mapped, check if any descendant is mapped
            has_mapped_child = False
            for ch in item.children:
                if any(k.startswith(ch.source_rel) or k == ch.source_rel for k in all_specs):
                    has_mapped_child = True
                    break
            if not has_mapped_child and not item.is_directory:
                item.is_excluded = True

        for ch in item.children:
            _apply_item(ch, parent_packed=parent_packed or is_packed_dir)

        # If a directory has active children but itself is not in all_specs, it was unpacked
        if item.is_directory:
            if src in all_specs:
                item.link_as_dir = True
                item.force_pack = True
            else:
                active_leaves = [l for l in get_all_leaf_items(item) if not l.is_excluded]
                if active_leaves:
                    item.link_as_dir = False
                    item.force_pack = False
                    item.is_excluded = False
                    item.customized = True
                elif src not in all_specs and any(src == k for k in ignore_set):
                    item.is_excluded = True

    for top_item in discovered:
        _apply_item(top_item)

    # Any manual mappings in template not discovered on disk by scanner
    for src, (dest, mode, os_target) in all_specs.items():
        if src not in matched_specs:
            discovered.append(DiscoveredConfig(
                app_name=Path(src).stem,
                source_rel=src,
                dest_expr=dest,
                is_directory=False,
                link_mode=mode,
                os_target=os_target,
                detection_source="existing template",
                customized=True,
                is_excluded=False,
            ))

    return discovered


def run_builder(
    target: Optional[str] = None,
    dest_dir: Optional[Path] = None,
    interactive: bool = True,
    is_system: bool = False,
    force_yes: bool = False,
) -> Optional[Path]:
    """Execute the Fig Build workflow."""
    mode_tag = "SYSTEM CONFIGURATION MODE" if is_system else f"User Dotfiles Mode ({CURRENT_OS.value.capitalize()})"
    print("=" * 90)
    print(f"Fig Template Builder — [{mode_tag}]")
    print("=" * 90)

    # 1. Resolve source repository
    if target:
        if is_git_url(target):
            repo_dir = clone_remote_repo(target, dest_dir=dest_dir, interactive=interactive)
        else:
            repo_dir = Path(target).resolve()
    else:
        cwd = Path.cwd().resolve()
        use_cwd = ask_bool(f"Use current directory ({cwd.name}) as config source of truth?", default=True) if interactive else True
        if use_cwd:
            repo_dir = cwd
        else:
            loc = ask_input("Enter path to dotfiles directory or Git URL")
            if not loc:
                print("No directory provided. Aborting builder.")
                return None
            if is_git_url(loc):
                repo_dir = clone_remote_repo(loc, dest_dir=dest_dir, interactive=interactive)
            else:
                repo_dir = Path(loc).resolve()

    if not repo_dir.is_dir():
        print(f"Error: Directory does not exist: {repo_dir}", file=sys.stderr)
        return None

    # Load existing template if present
    existing_tpl = None
    tpl_file = repo_dir / "fig.toml"
    if tpl_file.is_file():
        try:
            existing_tpl = Template.load(tpl_file)
        except Exception:
            pass

    # 2. Safety Warning if building system configs
    if is_system:
        confirmed = display_breaking_changes_warning(
            affected_paths=[],
            force_yes=force_yes,
            interactive=interactive,
        )
        if not confirmed:
            print("System builder aborted.")
            return None

    print(f"\nScanning repository tree at: {repo_dir} (Host: {CURRENT_OS.value.capitalize()})...")
    scanner = RepoScanner(repo_dir)
    discovered = scanner.scan(scan_system=is_system)

    if existing_tpl:
        discovered = merge_existing_template_into_discovered(discovered, existing_tpl)

    if not discovered:
        print("No standard configuration packages or pathspecs detected.")
        if interactive:
            add_man = ask_bool("Would you like to manually add a mapping?", default=False)
            if not add_man:
                return None
            src = ask_input("Relative source path in repo")
            dest = ask_input("Target destination expression (e.g. ~/.config/myapp)")
            discovered.append(DiscoveredConfig(
                app_name=Path(src).stem,
                source_rel=src,
                dest_expr=dest,
                is_directory=False,
            ))
        else:
            return None

    # 3. Interactive REPL review
    reviewed = run_builder_repl(discovered, interactive=interactive, is_system=is_system)
    if not reviewed:
        return None

    # 4. Assemble and save template
    template = build_template_from_items(
        repo_root=repo_dir,
        items=reviewed,
        is_system=is_system,
        existing_template=existing_tpl,
    )
    template.save(tpl_file)

    # 5. Register profile & active pointer in FigState
    timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
    default_profile = getattr(existing_tpl, "name", None) or f"unnamed_{timestamp_str}"
    if interactive and sys.stdin.isatty():
        chosen_profile = ask_input("Enter profile name for this configuration", default=default_profile)
    else:
        chosen_profile = default_profile

    state = FigState()
    pm = ProfileManager(state)
    pm.save_profile(chosen_profile, tpl_file, repo_root=repo_dir)
    state.set_active_template_path(tpl_file, repo_dir, profile_name=chosen_profile)

    log_operation(
        "build",
        "SUCCESS",
        f"Built template at {tpl_file} ({len(reviewed)} items, profile '{chosen_profile}' registered)",
        is_system=is_system,
    )

    print("\n" + render_banner("[SUCCESS] Template Generated & Registered as ACTIVE", f"Active Profile: '{chosen_profile}' -> {tpl_file}", width=90))
    print(f"   {c_bold('Profile Name:')}   {chosen_profile}")
    print(f"   {c_bold('Template File:')}  {tpl_file}")
    print(f"   {c_bold('Active Pointer:')} ~/.fig/state.toml -> {tpl_file}")
    print(f"   {c_bold('Active Link:')}    ~/.fig/active_template.toml -> {tpl_file}")
    print(c_cyan("=" * 90, bold=True))

    # 6. Offer immediate deployment
    if interactive and sys.stdin.isatty():
        deploy_now = ask_bool("\nWould you like to deploy and synchronize these links now?", default=True)
        if deploy_now:
            print("\nSynchronizing links to system...")
            engine = FigEngine(state)
            if is_system:
                res = SystemConfigManager(state).apply_system(template, repo_dir, force_yes=force_yes, dry_run=False)
            else:
                res = engine.apply(dry_run=False)

            action_title = "Synchronized" if not res.dry_run else "Preview Plan"
            print(f"\n--- {action_title} [{res.template_name}] ---")
            if res.created:
                print(f"Linked {len(res.created)} item(s):")
                for src, dest in res.created:
                    print(f"  {badge_created('+')} {dest} {c_dim('->')} {src}")
            if res.already_linked:
                print(f"Already synchronized ({len(res.already_linked)} item(s)):")
                for src, dest in res.already_linked:
                    print(f"  {badge_ok('=')} {dest}")
            if res.failed:
                print(f"Failures ({len(res.failed)}):")
                for src, dest, err in res.failed:
                    print(f"  {badge_conflict('!')} {dest}: {err}")
            print()
            log_operation(
                "apply",
                "SUCCESS" if res.is_success else "FAILED",
                f"Template: {res.template_name}, Created: {len(res.created)}",
                is_system=is_system,
            )
            return tpl_file

    print("\nYou can deploy or update your links at any time by running:")
    print(f"  {c_cyan('fig')}          (or 'fig apply')")
    print(f"  {c_cyan('fig check')}    (to inspect status)")
    print(c_cyan("=" * 90, bold=True))
    return tpl_file


def run_rebuilder(
    target: Optional[str] = None,
    interactive: bool = True,
    is_system: bool = False,
    force_yes: bool = False,
) -> Optional[Path]:
    """Execute the Fig Rebuild workflow.
    Rebuilds / edits the current active template (or specified target) directly
    inside the interactive Builder REPL, preserving custom mappings, destinations,
    link modes, and OS scopes without losing existing configurations.
    """
    mode_tag = "SYSTEM CONFIGURATION REBUILD" if is_system else f"Rebuilding Dotfiles Template ({CURRENT_OS.value.capitalize()})"
    print("=" * 90)
    print(f"Fig Template Rebuilder — [{mode_tag}]")
    print("=" * 90)

    state = FigState()

    # 1. Resolve source repository and template
    tpl_file: Optional[Path] = None
    repo_dir: Optional[Path] = None

    if target:
        cand_path = Path(target).resolve()
        if cand_path.is_file():
            tpl_file = cand_path
            repo_dir = cand_path.parent
        elif cand_path.is_dir():
            repo_dir = cand_path
            tpl_file = repo_dir / "fig.toml"
        else:
            print(f"Error: Target path does not exist: {target}", file=sys.stderr)
            return None
    else:
        # Check current working directory first
        cwd = Path.cwd().resolve()
        cwd_tpl = cwd / "fig.toml"
        if not cwd_tpl.exists():
            cwd_tpl = cwd / ".fig.toml"

        if cwd_tpl.is_file():
            tpl_file = cwd_tpl
            repo_dir = cwd
        else:
            # Fall back to current active template registered in FigState
            active_tpl = state.get_active_template_path()
            if active_tpl and active_tpl.is_file():
                tpl_file = active_tpl
                repo_dir = state.get_active_repo_root() or active_tpl.parent
            else:
                print("Error: No active template found to rebuild, and no 'fig.toml' in current directory.", file=sys.stderr)
                print("To create a new template from your dotfiles, run: fig build", file=sys.stderr)
                return None

    if not tpl_file or not tpl_file.is_file():
        print(f"Error: Template file does not exist: {tpl_file}", file=sys.stderr)
        return None

    if not repo_dir or not repo_dir.is_dir():
        print(f"Error: Repository root does not exist: {repo_dir}", file=sys.stderr)
        return None

    # Load existing template
    try:
        existing_tpl = Template.load(tpl_file)
    except Exception as e:
        print(f"Error loading template at {tpl_file}: {e}", file=sys.stderr)
        return None

    print(f"\nRebuilding template: {c_bold(tpl_file.name)} [{c_cyan(existing_tpl.name or 'template')}]")
    print(f"Repository source of truth: {repo_dir}")

    # 2. Safety Warning if building system configs
    if is_system:
        confirmed = display_breaking_changes_warning(
            affected_paths=[],
            force_yes=force_yes,
            interactive=interactive,
        )
        if not confirmed:
            print("System rebuilder aborted.")
            return None

    # 3. Scan repository & merge existing template settings
    print(f"\nScanning repository tree at: {repo_dir} (Host: {CURRENT_OS.value.capitalize()})...")
    scanner = RepoScanner(repo_dir)
    discovered = scanner.scan(scan_system=is_system)

    discovered = merge_existing_template_into_discovered(discovered, existing_tpl)

    # 4. Interactive REPL review (pre-populated with existing template)
    reviewed = run_builder_repl(discovered, interactive=interactive, is_system=is_system)
    if not reviewed:
        return None

    # 5. Assemble updated template
    template = build_template_from_items(
        repo_root=repo_dir,
        items=reviewed,
        is_system=is_system,
        existing_template=existing_tpl,
    )
    template.save(tpl_file)

    # 6. Register profile & active pointer in FigState
    timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
    default_profile = getattr(existing_tpl, "name", None) or f"unnamed_{timestamp_str}"
    if interactive and sys.stdin.isatty():
        chosen_profile = ask_input("Enter profile name for this configuration", default=default_profile)
    else:
        chosen_profile = default_profile

    pm = ProfileManager(state)
    pm.save_profile(chosen_profile, tpl_file, repo_root=repo_dir)
    state.set_active_template_path(tpl_file, repo_dir, profile_name=chosen_profile)

    log_operation(
        "rebuild",
        "SUCCESS",
        f"Rebuilt template at {tpl_file} ({len(reviewed)} items, profile '{chosen_profile}' updated)",
        is_system=is_system,
    )

    print("\n" + render_banner("[SUCCESS] Template Rebuilt & Registered as ACTIVE", f"Active Profile: '{chosen_profile}' -> {tpl_file}", width=90))
    print(f"   {c_bold('Profile Name:')}   {chosen_profile}")
    print(f"   {c_bold('Template File:')}  {tpl_file}")
    print(f"   {c_bold('Active Pointer:')} ~/.fig/state.toml -> {tpl_file}")
    print(f"   {c_bold('Active Link:')}    ~/.fig/active_template.toml -> {tpl_file}")
    print(c_cyan("=" * 90, bold=True))

    # 7. Offer immediate deployment
    if interactive and sys.stdin.isatty():
        deploy_now = ask_bool("\nWould you like to deploy and synchronize these updated links now?", default=True)
        if deploy_now:
            print("\nSynchronizing links to system...")
            engine = FigEngine(state)
            if is_system:
                res = SystemConfigManager(state).apply_system(template, repo_dir, force_yes=force_yes, dry_run=False)
            else:
                res = engine.apply(dry_run=False)

            action_title = "Synchronized" if not res.dry_run else "Preview Plan"
            print(f"\n--- {action_title} [{res.template_name}] ---")
            if res.created:
                print(f"Linked {len(res.created)} item(s):")
                for src, dest in res.created:
                    print(f"  {badge_created('+')} {dest} {c_dim('->')} {src}")
            if res.already_linked:
                print(f"Already synchronized ({len(res.already_linked)} item(s)):")
                for src, dest in res.already_linked:
                    print(f"  {badge_ok('=')} {dest}")
            if res.failed:
                print(f"Failures ({len(res.failed)}):")
                for src, dest, err in res.failed:
                    print(f"  {badge_conflict('!')} {dest}: {err}")
            print()
            log_operation(
                "apply",
                "SUCCESS" if res.is_success else "FAILED",
                f"Template: {res.template_name}, Created: {len(res.created)}",
                is_system=is_system,
            )
            return tpl_file

    print("\nYou can deploy or update your links at any time by running:")
    print(f"  {c_cyan('fig')}          (or 'fig apply')")
    print(f"  {c_cyan('fig check')}    (to inspect status)")
    print(c_cyan("=" * 90, bold=True))
    return tpl_file
